/*
 * Release signing comes ONLY from the environment (CI secrets) or an untracked keystore.properties file.
 * No keystore or password is ever committed. Without them, assembleRelease produces an unsigned APK.
 */
val signingProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? = System.getenv(env) ?: signingProps.getProperty(prop)
val releaseStoreFile = signingValue("AIEC_KEYSTORE", "storeFile")

